import type { AnalysisResponseData } from '../types.ts';

export function generateMarkdownReport(analysis: AnalysisResponseData): string {
  const dateStr = new Date(analysis.timestamp).toLocaleDateString();
  const timeStr = new Date(analysis.timestamp).toLocaleTimeString();

  return `# ResumeMatch AI Evaluation Report
**Target Role:** ${analysis.roleTitle || 'General Alignment'}
**Date:** ${dateStr} at ${timeStr}
**Model Used:** ${analysis.modelUsed} ${analysis.isFallback ? '(Fallback)' : ''}
**Overall Match Score:** ${analysis.overall_match_score}%
**Verdict:** ${analysis.verdict}
**Semantic Similarity (Embedding):** ${analysis.semantic_similarity?.overall_similarity || 'N/A'}%

---

## 1. Score Breakdown
- **Skills Match:** ${analysis.score_breakdown.skills_match.score}% — ${analysis.score_breakdown.skills_match.reason}
- **Experience Match:** ${analysis.score_breakdown.experience_match.score}% — ${analysis.score_breakdown.experience_match.reason}
- **Education Match:** ${analysis.score_breakdown.education_match.score}% — ${analysis.score_breakdown.education_match.reason}
- **Keywords & ATS:** ${analysis.score_breakdown.keywords_match.score}% — ${analysis.score_breakdown.keywords_match.reason}

---

## 2. Skills Analysis
### Matched Skills (${analysis.matched_skills.length}):
${analysis.matched_skills.map((s) => `- [x] ${s}`).join('\n')}

### Missing Skills (${analysis.missing_skills.length}):
${analysis.missing_skills.map((m) => `- [ ] ${m.skill} (Importance: ${m.importance.toUpperCase()})`).join('\n')}

### ATS Keyword Gaps:
${analysis.ats_keyword_gaps.map((k) => `- ${k}`).join('\n') || 'None detected.'}

---

## 3. Key Strengths
${analysis.strengths.map((s, idx) => `${idx + 1}. ${s}`).join('\n')}

## 4. Gaps & Areas for Growth
${analysis.weaknesses.map((w, idx) => `${idx + 1}. ${w}`).join('\n')}

---

## 5. Bullet Rewrite Suggestions
${analysis.rewrite_suggestions
  .map(
    (rw, idx) => `### Suggestion #${idx + 1}
**Original:**
> "${rw.original}"

**Improved:**
> "${rw.improved}"
${rw.critique ? `*Critique:* ${rw.critique}` : ''}
`
  )
  .join('\n')}

---

*Disclaimer: This is an AI estimate and not how every recruiter or ATS will score you.*
*Generated by ResumeMatch AI with Gemini API.*
`;
}

